/** انتخاب چند جملهٔ روز؛ با seed ثابت در یک روز، و با shift برای جملهٔ دیگر */
export function getDailyAffirmations(count = 4, shift = 0): string[] {
  const now = new Date();
  const dayIndex = Math.floor(
    Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) / 86400000
  );
  const start = (dayIndex * count + shift * count) % AFFIRMATIONS.length;
  return Array.from({ length: count }, (_, i) => AFFIRMATIONS[(start + i) % AFFIRMATIONS.length]);
}

export function getImportantReminder(): { title: string; text: string } {
  const h = new Date().getHours();
  if (h >= 5 && h < 12) {
    return {
      title: 'شروع آرام روز',
      text: 'پیش از غرق شدن در کارها، سه نفس آهسته بکش و یک قصد ساده برای امروز بساز.'
    };
  }
  if (h >= 12 && h < 17) {
    return {
      title: 'یک مکث کوتاه',
      text: 'شانه‌ها را شل کن، آب بنوش و یک دقیقه فقط به نفس‌هایت توجه کن.'
    };
  }
  if (h >= 17 && h < 21) {
    return {
      title: 'رها کردن شلوغی روز',
      text: 'وقتش است کارهای روز را کنار بگذاری؛ چند دقیقه موسیقی آرام و تنفس کند، ذهنت را سبک می‌کند.'
    };
  }
  return {
    title: 'آماده شدن برای خواب',
    text: 'نور صفحه را کم کن و با صدای آرام یا مدیتیشن کوتاه، به خواب آسوده نزدیک شو.'
  };
}
